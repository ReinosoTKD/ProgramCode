-- ProgramCode - Esquema para Supabase
-- Ejecutar completo en: Supabase Dashboard -> SQL Editor -> New query -> Run
-- Con RLS activado y SIN politicas publicas: solo la clave service_role
-- (usada unicamente por el servidor) puede leer y escribir.

create table if not exists public.models (
  id text primary key,
  name text not null,
  provider text not null default 'nvidia',
  base_url text not null,
  model text not null,
  api_key text not null,
  capacity text not null default '',
  system_prompt text not null default '',
  reasoning_effort text,
  is_auto boolean not null default false,
  is_available boolean not null default true,
  sort_order integer not null default 0,
  auto_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.chats (
  id uuid primary key default gen_random_uuid(),
  title text not null default 'Nuevo chat',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,

  chat_id uuid not null references public.chats(id) on delete cascade,
  role text not null check (role in ('user', 'assistant', 'system')),
  content text not null,
  model text,
  created_at timestamptz not null default now()
);

create index if not exists messages_chat_id_idx on public.messages (chat_id, id);
create index if not exists chats_updated_at_idx on public.chats (updated_at desc);

alter table public.models enable row level security;
alter table public.chats enable row level security;
alter table public.messages enable row level security;

-- No se crean politicas para anon/authenticated a proposito.
-- El servidor accede con la clave service_role, que omite RLS.

-- Permisos para la clave service_role (solo el servidor los usa).
-- RLS sigue activo y sin politicas publicas: anon no puede leer ni escribir.
grant usage on schema public to service_role;
grant all privileges on public.models to service_role;
grant all privileges on public.chats to service_role;
grant all privileges on public.messages to service_role;
grant usage, select on all sequences in schema public to service_role;

-- ---------------------------------------------------------------------------
-- Cuentas (Supabase Auth) y sesiones del servidor
-- Las contrasenas se guardan cifradas en auth.users; nunca en texto plano.
-- ---------------------------------------------------------------------------
alter table public.chats add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.messages add column if not exists user_id uuid references auth.users(id) on delete cascade;

create index if not exists chats_user_id_idx on public.chats (user_id, updated_at desc);
create index if not exists messages_user_id_idx on public.messages (user_id, chat_id, id);

create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  access_token text not null,
  refresh_token text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists sessions_user_id_idx on public.sessions (user_id);

alter table public.sessions enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.chats to authenticated;
grant select, insert, update, delete on public.messages to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant all privileges on public.sessions to service_role;
revoke all on public.models from anon, authenticated;
revoke all on public.sessions from anon, authenticated;

drop policy if exists "chats propios" on public.chats;
create policy "chats propios" on public.chats
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists "mensajes propios" on public.messages;
create policy "mensajes propios" on public.messages
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());
